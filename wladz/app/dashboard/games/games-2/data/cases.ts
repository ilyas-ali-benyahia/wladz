export type CaseTier = 1 | 2 | 3;

export type SceneTarget =
  | "classmate"
  | "classmates"
  | "bench"
  | "teacher"
  | "garden"
  | "basket"
  | "classroom"
  | "school-bag"
  | "notice-board"
  | "ball"
  | "water-fountain"
  | "phone";

export type CaseChoice = {
  id: string;
  label: string;
  feedback: string;
  score: 0 | 0.5 | 1;
};

export type CaseStep = {
  target: SceneTarget;
  targetLabel: string;
  dialogue: string;
};

export type SchoolCase = {
  id: string;
  tier: CaseTier;
  title: string;
  opening: string;
  question: string;
  steps: CaseStep[];
  choices: CaseChoice[];
};

function step(
  target: SceneTarget,
  targetLabel: string,
  dialogue: string,
): CaseStep {
  return { target, targetLabel, dialogue };
}

function choice(
  id: string,
  label: string,
  feedback: string,
  score: CaseChoice["score"],
): CaseChoice {
  return { id, label, feedback, score };
}

